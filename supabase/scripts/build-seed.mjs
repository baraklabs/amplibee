// Turns supabase/seed/directories.json into supabase/seed.sql (idempotent upserts).
//   node supabase/scripts/build-seed.mjs

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const rows = JSON.parse(await readFile(join(here, '../seed/directories.json'), 'utf8'))
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

const values = rows
  .map((d) => `  (${[q(d.slug), q(d.name), q(d.url), q(d.category), q(d.submit_url), q(d.check_method), q(d.check_url_template), d.priority, q(d.description), d.verified, q(d.todo), q(d.verified_at)].join(', ')})`)
  .join(',\n')

const sql = `-- Generated by supabase/scripts/build-seed.mjs from supabase/seed/directories.json. Do not edit by hand.
insert into public.directories
  (slug, name, url, category, submit_url, check_method, check_url_template, priority, description, verified, todo, verified_at)
values
${values}
on conflict (slug) do update set
  name = excluded.name, url = excluded.url, category = excluded.category, submit_url = excluded.submit_url,
  check_method = excluded.check_method, check_url_template = excluded.check_url_template, priority = excluded.priority,
  description = excluded.description, verified = excluded.verified, todo = excluded.todo, verified_at = excluded.verified_at;
`
await writeFile(join(here, '../seed.sql'), sql)
console.log(`wrote supabase/seed.sql with ${rows.length} directories`)
